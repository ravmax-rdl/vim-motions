export const commands: Command[] = sections.flatMap((section) =>
  section.entries.map((entry, index) => ({
    id: `${section.id}-${index}`,
    keys: entry.keys,
    description: entry.description,
    sectionId: section.id,
    sectionName: section.name,
    sectionShort: section.short,
    group: section.group,
  })),
);

export const commandCount = commands.length;

export function groupCount(group: GroupId | "all") {
  if (group === "all") return commands.length;
  return commands.filter((command) => command.group === group).length;
}
